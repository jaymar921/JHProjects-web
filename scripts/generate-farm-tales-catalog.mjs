/**
 * Writes the Farm Tales catalog table the page renders, out of the plugin's
 * own catalog files.
 *
 * The plugin is closed source, so the page is the only place a server owner
 * can read the whole catalog before installing it. Typing 134 rows by hand
 * would be 134 chances to drift from what the jar ships, so this reads the
 * three shipped YAML files and writes FTCatalog.js. Rerun it whenever a
 * release adds or changes an entry; the output is committed because the
 * plugin repository is private and the site's build cannot reach it.
 *
 *   node scripts/generate-farm-tales-catalog.mjs [path-to-Farm_Tales-repo]
 *
 * Defaults to the sibling checkout at F:/important stuff/Programming/JAVA/
 * Farm_Tales. Only the fields the page shows are kept: id, display name,
 * kind, growth form, base growth time, the vanilla item it rides on, the
 * nutrition profile, whether the free edition has it, and whether it brews.
 * Meat carries no `lite` key on purpose (the plugin derives it from the
 * animal and the grade), so the Lite answer for meat is computed here the
 * same way the plugin computes it: cow and chicken, at Common and Good.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PLUGIN = resolve(
  process.argv[2] ?? "F:/important stuff/Programming/JAVA/Farm_Tales",
);
const CATALOG = resolve(PLUGIN, "src/main/resources/catalog");
const OUT = resolve(ROOT, "src/components/contants/farm_tales/FTCatalog.js");

const LITE_ANIMALS = new Set(["cow", "chicken"]);
const LITE_GRADES = new Set(["COMMON", "GOOD"]);

const title = (s) =>
  String(s)
    .toLowerCase()
    .replace(/_/g, " ")
    .replace(/\b\w/g, (c) => c.toUpperCase());

function readFile(name) {
  const doc = yaml.load(readFileSync(resolve(CATALOG, name), "utf8"));
  return Object.entries(doc.entries ?? {}).map(([id, e]) => {
    const kind = String(e.kind).toLowerCase();
    const isMeat = kind === "meat";
    const lite = isMeat
      ? LITE_ANIMALS.has(String(e.animal).toLowerCase()) &&
        LITE_GRADES.has(String(e.grade).toUpperCase())
      : e.lite === true;
    return {
      id,
      name: String(e.display).replace(/&[0-9a-fk-or]/gi, ""),
      kind,
      form: isMeat ? "meat" : String(e["growth-form"] ?? "CROP").toLowerCase(),
      growth: isMeat ? null : Number(e["base-growth-seconds"]),
      rides: title(e["base-item"]),
      animal: isMeat ? title(e.animal) : null,
      grade: isMeat ? title(e.grade) : null,
      nutrition: Object.entries(e.nutrition ?? {}).map(
        ([tag, amount]) => `${title(tag)} ${amount}`,
      ),
      lite,
      brewing: e.brewing === true,
    };
  });
}

const entries = [
  ...readFile("vegetables.yml"),
  ...readFile("fruits.yml"),
  ...readFile("meat.yml"),
];

const count = (kind) => entries.filter((e) => e.kind === kind).length;
const liteCount = entries.filter((e) => e.lite).length;

const header = `/**
 * The Farm Tales catalog, every entry the 1.0.0 jar ships.
 *
 * GENERATED by scripts/generate-farm-tales-catalog.mjs from the plugin's own
 * catalog/*.yml. Do not edit by hand; rerun the script.
 *
 * ${entries.length} entries: ${count("vegetable")} vegetables, ${count("fruit")} fruits, ${count("meat")} meats.
 * ${liteCount} of them are in the free Lite edition.
 *
 * growth is base-growth-seconds before the global multiplier, water and
 * fertilizer. form is crop (on farmland), potted (in a flower pot), tree (a
 * fruit tree the plugin builds) or meat. rides is the vanilla item the entry
 * sits on when there is no resource pack.
 */

export const FTCatalog = `;

writeFileSync(
  OUT,
  `${header}${JSON.stringify(entries, null, 2)};\n\nexport const FTCatalogCounts = ${JSON.stringify(
    {
      total: entries.length,
      vegetables: count("vegetable"),
      fruits: count("fruit"),
      meats: count("meat"),
      lite: liteCount,
      trees: entries.filter((e) => e.form === "tree").length,
      potted: entries.filter((e) => e.form === "potted").length,
      brewing: entries.filter((e) => e.brewing).length,
    },
    null,
    2,
  )};\n`,
  "utf8",
);

console.log(
  `wrote ${entries.length} entries (${liteCount} lite) to src/components/contants/farm_tales/FTCatalog.js`,
);
